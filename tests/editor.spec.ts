import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ page }) => {
  page.on('dialog', dialog => dialog.accept())
  await page.goto('./')
  await expect(page.getByLabel('Texto original')).toBeVisible()
})

test('escreve, marca melisma, desfaz, refaz e restaura após recarga', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.getByLabel('Título do texto').fill('Canção do intervalo')
  await page.getByLabel('Texto original').fill('a-mor e canção\n\nvoz')
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  await page.getByRole('button', { name: 'Sílaba a, verso 1', exact: true }).click()
  await page.getByLabel('Anotação', { exact: true }).fill('Sustentar três notas')
  await page.getByRole('button', { name: 'Melisma', exact: true }).click()
  await expect(page.locator('.unit.selected span')).toHaveCSS('text-decoration-style', 'wavy')
  await page.getByRole('button', { name: 'Desfazer', exact: true }).click()
  await expect(page.locator('.unit').first().locator('span')).not.toHaveCSS('text-decoration-style', 'wavy')
  await page.getByRole('button', { name: 'Refazer', exact: true }).click()
  await expect(page.locator('.unit').first().locator('span')).toHaveCSS('text-decoration-style', 'wavy')
  await page.getByRole('button', { name: 'Centralizar', exact: true }).click()
  await page.getByLabel('Separar sílabas').check()
  await expect(page.getByRole('status')).toHaveText('Salvo neste navegador')
  await page.screenshot({ path: testInfo.outputPath('marcacoes.png'), fullPage: true })
  await page.reload()
  await expect(page.getByLabel('Título do texto')).toHaveValue('Canção do intervalo')
  await expect(page.getByLabel('Texto original')).toHaveValue('a-mor e canção\n\nvoz')
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  await expect(page.locator('.unit').first().locator('span')).toHaveCSS('text-decoration-style', 'wavy')
  await expect(page.getByLabel('Separar sílabas')).toBeChecked()
  expect(errors).toEqual([])
})

