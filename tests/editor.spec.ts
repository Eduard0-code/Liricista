test('exporta e reimporta o projeto completo e baixa DOCX', async ({ page }, testInfo) => {
  await page.getByLabel('Texto original').fill('a-mor\nvoz')
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  await page.locator('.unit').first().click()
  await page.getByRole('button', { name: 'Melisma', exact: true }).click()
  await page.locator('.export-menu summary').click()
  const projectDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: /Projeto completo/ }).click()
  const backup = await projectDownload
  const projectPath = testInfo.outputPath('backup.liricista.json')
  await backup.saveAs(projectPath)
  const data = JSON.parse(await readFile(projectPath, 'utf8'))
  expect(data.marks[0].kind).toBe('melisma')
  const docxDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: /Documento Word/ }).click()
  const docx = await docxDownload
  const docxPath = testInfo.outputPath('versos.docx')
  await docx.saveAs(docxPath)
  expect((await readFile(docxPath)).subarray(0, 2).toString()).toBe('PK')
  await page.getByLabel('Importar arquivo').setInputFiles(docxPath)
  await expect(page.getByLabel('Texto original')).toHaveValue(/amor/)
  await expect(page.getByLabel('Texto original')).toHaveValue(/Anotações/)
  await page.getByRole('button', { name: 'Novo texto', exact: true }).click()
  await page.getByLabel('Importar arquivo').setInputFiles(projectPath)
  await expect(page.getByLabel('Texto original')).toHaveValue('a-mor\nvoz')
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  await expect(page.locator('.unit').first().locator('span')).toHaveCSS('text-decoration-style', 'wavy')
})

test('importa TXT literalmente e mostra falhas de arquivo', async ({ page }) => {
  await page.getByLabel('Importar arquivo').setInputFiles({ name: 'versos.txt', mimeType: 'text/plain', buffer: Buffer.from('*voz*\nco-autor') })
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  await expect(page.locator('.score')).toContainText('*voz*')
  await expect(page.locator('.score')).toContainText('co-autor')
  await page.getByLabel('Importar arquivo').setInputFiles({ name: 'ruim.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.score')).toContainText('*voz*')
})

test('não relata salvamento quando IndexedDB está indisponível', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(window, 'indexedDB', { get() { throw new Error('Armazenamento bloqueado') } })
  })
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('restaurar')
  await page.getByLabel('Texto original').fill('Não perder este verso')
  await expect(page.getByRole('status')).toHaveText('Falha ao salvar')
  await expect(page.getByRole('alert')).toContainText('Baixe o projeto')
  await expect(page.getByLabel('Texto original')).toHaveValue('Não perder este verso')
})

test('layout mantém painel no lugar e texto dentro da tela', async ({ page }, testInfo) => {
  await page.getByRole('tab', { name: 'Marcar', exact: true }).click()
  const score = await page.locator('.score-surface').boundingBox()
  const panel = await page.locator('.mark-panel').boundingBox()
  expect(score).not.toBeNull()
  expect(panel).not.toBeNull()
  if (testInfo.project.name === 'mobile') expect(panel!.y).toBeGreaterThanOrEqual(score!.y + score!.height - 1)
  else expect(panel!.x).toBeGreaterThanOrEqual(score!.x + score!.width - 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('layout.png'), fullPage: true })
  await page.getByRole('tab', { name: 'Escrever', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('escrita.png'), fullPage: true })
})